export const bestSellers = BEST_SELLER_IDS.map(getProduct);

export const relatedTo = (product, limit = 3) =>
  products.filter((p) => p.category === product.category && p.id !== product.id).slice(0, limit);

export const priceBounds = products.reduce(
  (acc, p) => ({ min: Math.min(acc.min, p.price), max: Math.max(acc.max, p.price) }),
  { min: Infinity, max: 0 },
);

